// v88.3 验证（合成夹具数据，非用户数据；Playwright Chrome 390 宽，非真机）：今日一行摘要 → 健康页手表日内（曲线/点按读数/日期切换/详情）+ 空状态。
import {chromium} from 'playwright'
import {readFileSync} from 'node:fs'
const base=process.argv[2], dir=process.argv[3]||'/workspace/out/v88.3', seed=readFileSync(process.argv[4]||'/tmp/v883-seed.json','utf8')
const b=await chromium.launch({executablePath:'/usr/bin/google-chrome',headless:true,args:['--no-sandbox']})
async function page(withSeed){const ctx=await b.newContext({viewport:{width:390,height:844},timezoneId:'Asia/Shanghai',isMobile:true,hasTouch:true})
 await ctx.route('**/api/garmin/**',r=>r.fulfill({status:200,contentType:'application/json',body:'{"loggedIn":false}'}));await ctx.route('**/api/coach-chat**',r=>r.fulfill({status:503,body:'{}'}))
 await ctx.addInitScript(([s,w])=>{if(!sessionStorage.getItem('qa')){sessionStorage.setItem('qa','1');localStorage.setItem('fk-onboard-v1','1');if(w)localStorage.setItem('fk-garmin-intraday-v1:local',s)}},[seed,withSeed])
 const p=await ctx.newPage();p.setDefaultTimeout(15000);p.on('pageerror',e=>console.log('PAGEERR',e.message));await p.goto(base);await p.locator('[data-testid="training-app"][data-ready=true]').waitFor({timeout:60000});await p.waitForTimeout(1500);return p}
const shot=(p,n)=>p.screenshot({path:`${dir}/${n}.png`})
const center=async(l)=>{await l.evaluate(e=>e.scrollIntoView({block:'start'}));await l.page().waitForTimeout(500)}
let p=await page(true)
console.log('SW caches:',await p.evaluate(async()=>{await navigator.serviceWorker?.ready;return (await caches.keys()).join(',')}))
const line=p.getByTestId('intraday-today-line');console.log('今日一行:',await line.count()?await line.innerText():'无')
await shot(p,'v883-1-today-line-390')
await line.tap();await p.waitForTimeout(1500)
const panel=p.getByTestId('intraday-panel');console.log('点后到健康页:',await panel.isVisible()?'是':'否')
await center(panel);await shot(p,'v883-2-health-intraday-390')
console.log('面板:',(await panel.innerText()).replace(/\n/g,' / ').slice(0,260))
const svg=p.getByTestId('intraday-hr').locator('svg[role=img]');const bx=await svg.boundingBox();await p.touchscreen.tap(bx.x+bx.width*0.6,bx.y+bx.height/2);await p.waitForTimeout(300)
console.log('点按读数:',await p.getByTestId('pick-label').first().innerText().catch(()=>'无'))
await shot(p,'v883-3-tap-value-390')
await p.getByRole('button',{name:'10月19日'}).first().tap();await p.waitForTimeout(500)
console.log('10-19 训练阴影:',await p.getByTestId('shade-training').count(),'睡眠阴影:',await p.getByTestId('shade-sleep').count())
await center(panel);await shot(p,'v883-4-date-switch-1019-390')
await p.getByRole('button',{name:'查看全天心率详情'}).tap();await p.waitForTimeout(800)
const dlg=p.getByRole('dialog',{name:'全天心率详情'});console.log('心率详情:',(await dlg.innerText()).replace(/\n/g,' / ').slice(0,240))
const dsvg=dlg.locator('svg[role=img]');const db=await dsvg.boundingBox();await p.touchscreen.tap(db.x+db.width*0.76,db.y+db.height/2);await p.waitForTimeout(300)
await shot(p,'v883-5-hr-detail-390')
await dlg.getByRole('button',{name:'关闭'}).tap();await p.waitForTimeout(400)
await p.getByRole('button',{name:'10月20日'}).first().tap();await p.waitForTimeout(300)
await p.getByRole('button',{name:'查看身体电量详情'}).tap();await p.waitForTimeout(800)
const dlg2=p.getByRole('dialog',{name:'身体电量详情'});console.log('电量详情:',(await dlg2.innerText()).replace(/\n/g,' / ').slice(0,300))
await shot(p,'v883-6-bb-detail-390')
p=await page(false)
console.log('空状态今日一行:',await p.getByTestId('intraday-today-line').count()?'有(错)':'不显示')
await p.getByRole('button',{name:'切换到健康'}).click();await p.waitForTimeout(1200)
const e=p.getByTestId('intraday-empty');console.log('空状态:',await e.count()?await e.innerText():'无')
await center(p.getByTestId('intraday-panel'));await shot(p,'v883-7-empty-390')
await b.close()
