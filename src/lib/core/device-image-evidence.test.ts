import test from 'node:test'
import assert from 'node:assert/strict'
import {parseDeviceEvidence, validateDeviceConfirmation, makeDeviceRecord, validReading} from './device-image-evidence.ts'
const parse=(text:string)=>parseDeviceEvidence(text).readings
const iso='2026-10-10T06:00:00+08:00'
test('睡眠7小时25分保留分钟精度',()=>{const r=parse('睡眠 7小时25分');assert.equal(r.length,1);assert.ok(Math.abs(r[0]!.value-7.4166667)<0.001)})
test('睡眠7:25解析为小时而不是运动分段',()=>assert.equal(parse('Sleep 7:25')[0]?.metric,'SLEEP_HOURS'))
test('睡眠23小时仍保留但25小时拒绝',()=>{assert.equal(parse('睡眠 23小时').length,1);assert.equal(parse('睡眠 25小时').length,0)})
test('HRV ms 单位明确',()=>assert.deepEqual(parse('HRV: 62ms').map(r=>[r.metric,r.value]),[['HRV_MS',62]]))
test('无单位HRV不猜',()=>assert.equal(parse('HRV: 62').length,0))
test('静息心率',()=>assert.equal(parse('静息心率 49 bpm')[0]?.metric,'RESTING_HR_BPM'))
test('RHR英文',()=>assert.equal(parse('RHR 52')[0]?.value,52))
test('平均心率',()=>assert.equal(parse('平均心率 151 bpm')[0]?.metric,'AVERAGE_HR_BPM'))
test('普通心率不误判为静息',()=>assert.equal(parse('心率 151')[0],undefined))
test('体重',()=>assert.equal(parse('体重 65.4kg')[0]?.value,65.4))
test('体脂',()=>assert.equal(parse('体脂率 12.8%')[0]?.value,12.8))
test('血氧',()=>assert.equal(parse('SpO2 97%')[0]?.value,97))
test('设备评分不是HRV',()=>assert.equal(parse('HRV 状态 平衡 62分').length,0))
test('未标记体重不推断',()=>assert.equal(parse('65.4kg').length,0))
test('错误体重范围被拒绝',()=>assert.equal(parse('体重 850kg').length,0))
test('分段400米68秒含心率恢复',()=>{const r=parse('第1段 400m 68.2s 心率168 恢复120s')[0]!;assert.equal(r.metric,'RUN_SPLIT');assert.equal(r.value,68.2);assert.equal(r.details?.distanceMeters,400);assert.equal(r.details?.heartRateBpm,168);assert.equal(r.details?.recoverySeconds,120)})
test('分段1公里3:45',()=>{const r=parse('Lap 2 1km 3:45')[0]!;assert.equal(r.value,225);assert.equal(r.details?.distanceMeters,1000)})
test('没有时间不把距离当已完成',()=>assert.equal(parse('第1段 400m')[0],undefined))
test('分段重复训练保留每段',()=>assert.equal(parse('第1段 200m 28s\n第2段 200m 29s').length,2))
test('异常80000米不采纳',()=>assert.equal(parse('第1段 80000m 68s').length,0))
test('力量实际组重量次数',()=>{const r=parse('深蹲 第2组 60kg x 8次')[0]!;assert.equal(r.metric,'STRENGTH_SET');assert.equal(r.value,60);assert.equal(r.details?.repetitions,8);assert.equal(r.details?.setOrdinal,2)})
test('力量没有次数不采纳',()=>assert.equal(parse('深蹲 第2组 60kg').length,0))
test('同一行两个指标分别记录',()=>assert.equal(parse('HRV 62ms 静息心率 49bpm').length,2))
test('多行混合',()=>assert.equal(parse('体重 65.4kg\n睡眠 7小时\nHRV 60ms').length,3))
test('空文本提示缺证据',()=>assert.match(parseDeviceEvidence(' ').warnings.join(''),/没有识别到/))
test('重复截图数字发出警告',()=>assert.ok(parseDeviceEvidence('体重 65kg\n体重 65kg').warnings.some(w=>w.includes('疑似重复'))))
test('无来源不能确认',()=>assert.ok(validateDeviceConfirmation({draft:parseDeviceEvidence('体重 65kg'),deviceLabel:'',recordedAt:iso,acknowledged:true}).length>0))
test('无时区不能确认',()=>assert.ok(validateDeviceConfirmation({draft:parseDeviceEvidence('体重 65kg'),deviceLabel:'智能秤',recordedAt:'2026-10-10T06:00',acknowledged:true}).length>0))
test('必须人工确认',()=>assert.ok(validateDeviceConfirmation({draft:parseDeviceEvidence('体重 65kg'),deviceLabel:'智能秤',recordedAt:iso,acknowledged:false}).length>0))
test('重复值禁止确认',()=>assert.ok(validateDeviceConfirmation({draft:parseDeviceEvidence('体重 65kg\n体重 65kg'),deviceLabel:'智能秤',recordedAt:iso,acknowledged:true}).some(x=>x.includes('重复'))))
test('合法记录只保存证据不改训练',()=>{const r=makeDeviceRecord({draft:parseDeviceEvidence('体重 65kg'),deviceLabel:'智能秤',recordedAt:iso,acknowledged:true,imageName:'scale.png',imageSha256:'abc',confirmedAt:iso,id:'id-1'});assert.equal(r.destination,'DEVICE_EVIDENCE_ONLY');assert.equal(r.consent,'USER_CONFIRMED');assert.equal(r.readings.length,1)})
test('无效数值被拒绝',()=>assert.equal(validReading({...parse('体重 65kg')[0]!,value:Infinity}),false))
test('未知字符串不会虚构',()=>assert.equal(parse('今天有点累，腿酸，建议减量吗').length,0))
