/** 结构名标准化：去掉 Left/Right、编号后缀，便于左右合并。 */
export const normStructure = name => String(name || '').toLowerCase().replace(/\b(left|right)\s+/g, '').replace(/\s*\(\d\)$/, '').replace(/\s+/g, ' ').trim();
export const SIDE_ZH = { left: '左侧', right: '右侧' };
/** @returns {{zh:string, base:string, train:string[], fn:string, fascia:boolean, pending:boolean, face:boolean, nonTarget:boolean, rel:string}|null} */
export function zhStructure(data) {
  const row = ANATOMY_ZH[normStructure(data?.name)]; if (!row) return null;
  const [base, train, fn, flags = '', rel = ''] = row;
  return { base, zh: (SIDE_ZH[data.side] || '') + base, train: train ? train.split(',') : [], fn, fascia: flags.includes('f'), pending: flags.includes('p'), face: flags.includes('h'), nonTarget: flags.includes('n'), rel };
}
